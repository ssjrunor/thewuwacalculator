/*
  Author: Runor Ewhro
  description: hashes a ruleset's scoring inputs: the bundled engine functions the scorer calls (scoring, rotation
               execution, card stats, best-scenario choice, excluding the queue and database code around them, which
               cannot change a score) and every file of the ruleset package with the ruleset's own id removed
               (scenario ids include it). rulesets with equal fingerprints score every build the same, so a rollout
               over an unchanged one is skipped. LEADERBOARD_ENGINE_VER and ROTATION_GEN_VER are the labels a scorer
               checks, and this hash selects when a rescore is needed.
*/

import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { extname, resolve } from 'node:path'
import { build, transform } from 'esbuild'
import { resonatorForms, rulesetJson } from './engine.mjs'

const service = resolve(import.meta.dirname, '../..')
const sha256 = (data) => createHash('sha256').update(data).digest('hex')

// the exports that turn a build into a score as the scorer bundles them, with paths relative to the service, so
// every checkout hashes the same
export const SCORING_EXPORTS = ['openRuleset', 'openScoringSession', 'scoreScenario', 'executeScoringRotation', 'offlineAnchorExecutor',
  'buildScore', 'anchorStateFor', 'scenarioReads', 'cardBuildStats', 'pickBest']

// bundle options shared by every code hash; minifyWhitespace drops comments, so comment edits leave the hashes
// unchanged
const bundleOptions = (contents) => ({
  stdin: { contents, resolveDir: service },
  absWorkingDir: service, alias: { '@': resolve(service, '../../src') },
  bundle: true, write: false, platform: 'node', format: 'esm', logLevel: 'silent', legalComments: 'none', minifyWhitespace: true,
})

const SCORING_ENTRY = `export { ${SCORING_EXPORTS.join(', ')} } from '@/engine/leaderboard'`

export async function scorerBundleHash() {
  const result = await build(bundleOptions(SCORING_ENTRY))
  return sha256(result.outputFiles[0].contents)
}

const LOADERS = { '.ts': 'ts', '.tsx': 'tsx', '.js': 'js', '.mjs': 'js', '.jsx': 'jsx' }

// a source file's content with comments and whitespace stripped (esbuild transform); other files hash as stored
async function codeOf(path) {
  const text = await readFile(resolve(service, path))
  const loader = LOADERS[extname(path)]
  if (!loader) return text
  return (await transform(text.toString('utf8'), { loader, minifyWhitespace: true, legalComments: 'none' })).code
}

// the scorer hash in two parts by its bundle's source files, each hashed without comments: the generator (every file
// under src/engine/rotationGen) and evaluation (every other file). two scorers with the same evaluation part differ
// only in how programs are made, so scores with an unchanged program still apply (scorer/reuse.ts). files outside
// that folder count as evaluation, even when only the generator imports them
export async function scorerParts() {
  const result = await build({ ...bundleOptions(SCORING_ENTRY), metafile: true })
  const generator = [], evaluation = []
  for (const path of Object.keys(result.metafile.inputs).sort()) {
    if (path === '<stdin>') continue
    const line = `${path} ${sha256(await codeOf(path))}`
    ;(/(^|\/)src\/engine\/rotationGen\//.test(path) ? generator : evaluation).push(line)
  }
  return { scorer: sha256(result.outputFiles[0].contents), generator: sha256(generator.join('\n')), evaluation: sha256(evaluation.join('\n')) }
}

// the rotation generator's code, bundled alone: what a stored rotation was generated by (rotationStore.ts)
export async function generatorBundleHash() {
  const result = await build(bundleOptions(`export { interpretTeamActions, createInterpreterEnvironment } from '@/engine/rotationGen'`))
  return sha256(result.outputFiles[0].contents)
}

// the manifest's file list without the result files (refs, offline anchors): they are outputs over the rest
function withoutResults({ anchors: _anchors, units: _units, ...files }) {
  return { ...files, refs: null }
}

// a package fingerprint from { manifest, files } as returned by readRulesetFolder or assembleRuleset. reference
// values (refs) are excluded because they are the scorer's output over the same inputs and do not exist yet at
// fingerprinting; a package read from disk hashes like the same package just assembled
export async function rulesetFingerprint({ manifest, files }, scorer) {
  const strip = (text) => text.replaceAll(manifest.id, '<ruleset>')
  // the id, file hashes and game version label do not affect scoring; canonical json makes key order irrelevant
  const { id: _id, hashes: _hashes, gameVer: _gameVer, ...rest } = manifest
  const parts = [`scorer ${scorer ?? await scorerBundleHash()}`,
    `manifest ${sha256(strip(rulesetJson({ ...rest, files: withoutResults(rest.files) })))}`]
  const refs = manifest.files?.refs
  const anchors = manifest.files?.anchors
  const units = manifest.files?.units
  for (const path of [...files.keys()].filter((p) => p !== 'manifest.json' && p !== refs && p !== units && !(anchors && p.startsWith(anchors))).sort()) {
    const value = files.get(path)
    parts.push(`${path} ${sha256(strip(Buffer.isBuffer(value) ? value.toString('utf8') : String(value)))}`)
  }
  return sha256(parts.join('\n'))
}

// per-scenario fingerprints: a data change touches a few resonators or weapons, and each scenario reads only its own
// members (and their rover forms), the scenario weapon, its teammates' weapons, and its team's plan and builds. a
// scenario fingerprint covers the scorer, every file without an entity owner, and its entities' files and entries;
// equal fingerprints score the scenario the same, so old scores can be kept (score/job.ts). a missed read would keep
// a stale score while an extra file costs only a rescore, so files without a clear entity owner are shared. echoes
// and sets are the build's: a scenario reads only those its teammate builds wear, and a scored build's own are in
// each score's reads, which the rollout's reuse check compares with the new units per build (scorer/reuse.ts
// readsHold). a change to one echo's data then rescores only the builds that wear it

// folders of one file per entity, named by its id
export const ENTITY_DIRS = [
  ['data/resonators/runtime-bundles/', 'resonator'], ['data/resonators/worker-bundles/', 'resonator'],
  ['interpreter/characters/', 'resonator'], ['data/weapons/runtime-bundles/', 'weapon'],
]

const OWNER_KINDS = { resonator: 'resonator', weapon: 'weapon', echo: 'echo', echoSet: 'set' }
const sourceOwner = (source) => OWNER_KINDS[source?.type] ? [OWNER_KINDS[source.type], String(source.id)] : null

// shared files with an owner per entry: `split(value, owner)` passes each entry to owner(kind, id) (or to the file's
// shared rest when it names none) and returns the remainder of the file as the rest
export const SPLIT = {
  'data/resonators/catalog.json': (list, owner) => list.filter((entry) => !owner(entry, 'resonator', entry.id)),
  'data/resonators/picker-catalog.json': (list, owner) => list.filter((entry) => !owner(entry, 'resonator', entry.id)),
  'data/resonators/damage-entries.json': (list, owner) => list.filter((entry) => !owner(entry, 'resonator', entry.resonatorId)),
  'data/resonators/details.json': (byId, owner) => Object.fromEntries(Object.entries(byId).filter(([id, entry]) => !owner(entry, 'resonator', id))),
  'data/resonators/sources.json': (list, owner) => list.filter((entry) => !owner(entry, ...sourceOwner(entry.source) ?? [])),
  'data/resonators/feature-ids.json': (list, owner, ctx) => list.filter((id) => !owner(id, 'resonator', ctx.featureOwner(id))),
  'data/source-manifest.json': ({ featureIds, sources, ...rest }, owner, ctx) => ({ ...rest,
    featureIds: featureIds.filter((id) => !owner(id, 'resonator', ctx.featureOwner(id))),
    sources: sources.filter((source) => !owner(source, ...sourceOwner(source) ?? [])) }),
  'data/weapons/catalog.json': (list, owner) => list.filter((entry) => !owner(entry, 'weapon', entry.id)),
  'data/weapons/core-catalog.json': ({ weapons, ...rest }, owner) => ({ ...rest, weapons: weapons.filter((entry) => !owner(entry, 'weapon', entry.id)) }),
  'data/weapons/sources.json': (list, owner) => list.filter((entry) => !owner(entry, ...sourceOwner(entry.source) ?? [])),
  'data/echoes/catalog.json': (list, owner) => list.filter((entry) => !owner(entry, 'echo', entry.id)),
  'data/echoes/sources.json': (list, owner) => list.filter((entry) => !owner(entry, ...sourceOwner(entry.source) ?? [])),
  'data/sonata/sets.json': (list, owner) => list.filter((entry) => !owner(entry, 'set', entry.id)),
  'data/sonata/effects.json': (list, owner) => list.filter((entry) => !owner(entry, 'set', entry.id)),
  'interpreter/characters/index.json': ({ rulesets, ...rest }, owner) => ({ ...rest,
    rulesets: Object.fromEntries(Object.entries(rulesets ?? {}).filter(([id, entry]) => !owner(entry, 'resonator', id))) }),
  'interpreter/gear/triggers.json': ({ weapons, echoes, sonatas, ...rest }, owner) => ({ ...rest,
    weapons: Object.fromEntries(Object.entries(weapons ?? {}).filter(([id, entry]) => !owner(entry, 'weapon', id))),
    echoes: Object.fromEntries(Object.entries(echoes ?? {}).filter(([id, entry]) => !owner(entry, 'echo', id))),
    sonatas: Object.fromEntries(Object.entries(sonatas ?? {}).filter(([id, entry]) => !owner(entry, 'set', id))) }),
}

// what a scenario reads of the entities: 'resonator:<id>', 'weapon:<id>', and the 'echo:<id>' and 'set:<id>' its
// teammate builds wear, sorted, and its teammate builds
export function scenarioEntities(def, teammates) {
  const resonators = new Set(def.members.flatMap((member) => resonatorForms(member.resonatorId)))
  const slots = new Set(def.members.map((member) => member.teamSlot).filter(Boolean))
  // teammate builds named by a seat of this team, under whichever form they are filed
  const builds = Object.entries(teammates.resonators ?? {}).filter(([id, entry]) =>
    resonators.has(id) || entry.builds.some((build) => build.outfits.some((outfit) => outfit.teams.some((team) => slots.has(team)))))
  for (const [id] of builds) for (const form of resonatorForms(id)) resonators.add(form)
  const weapons = new Set([String(def.weapon.id), ...builds.flatMap(([, entry]) => entry.builds.map((build) => String(build.weapon)))])
  const outfits = builds.flatMap(([, entry]) => entry.builds.flatMap((build) => build.outfits ?? []))
  const gear = new Set(outfits.flatMap((outfit) => [...outfit.mainEcho != null ? [`echo:${outfit.mainEcho}`] : [],
    ...(outfit.sets ?? []).map(([id]) => `set:${id}`)]))
  return { entities: [...[...resonators].map((id) => `resonator:${id}`), ...[...weapons].map((id) => `weapon:${id}`), ...gear].sort(), builds }
}

// each scenario's fingerprint with the scorer, by scenario id without the ruleset ('<resonator>:<team>:<weapon>');
// `pkg` is { manifest, files } as for rulesetFingerprint, and `data` is scenarioDataFingerprints(pkg) when available
export async function scenarioFingerprints(pkg, scorer, data) {
  const hashed = scorer ?? await scorerBundleHash()
  return Object.fromEntries(Object.entries(data ?? await scenarioDataFingerprints(pkg)).map(([key, fp]) => [key, sha256(`scorer ${hashed}\n${fp}`)]))
}

// each scenario's fingerprint without the scorer: only the data it reads
export async function scenarioDataFingerprints({ manifest, files }) {
  const strip = (text) => text.replaceAll(manifest.id, '<ruleset>')
  const text = (path) => { const value = files.get(path); return Buffer.isBuffer(value) ? value.toString('utf8') : String(value) }
  const hash = (value) => sha256(strip(rulesetJson(value)))
  const parse = (path) => JSON.parse(text(path))
  const list = (path) => files.has(path) ? parse(path) : []
  // an entity is one the catalogs name; an owner they do not name is not one, and its entries stay shared
  const known = { resonator: new Set(list('data/resonators/catalog.json').map((entry) => String(entry.id))),
    weapon: new Set(list('data/weapons/catalog.json').map((entry) => String(entry.id))),
    echo: new Set(list('data/echoes/catalog.json').map((entry) => String(entry.id))),
    set: new Set(list('data/sonata/sets.json').map((entry) => String(entry.id))) }
  const damageOwner = new Map(list('data/resonators/damage-entries.json').map((entry) => [String(entry.id), String(entry.resonatorId)]))
  // 'damage:<resonator>:…' or 'damage:<damage entry>…'; any other feature (an echo's) is shared
  const ctx = { featureOwner(id) { const n = /^damage:(\d+)/.exec(id)?.[1]; return n ? (known.resonator.has(n) ? n : damageOwner.get(n)) : undefined } }

  // each split file as its shared rest plus, per entity, its entries in file order and where it first appears
  const owned = new Map()
  const shared = []
  for (const [path, split] of Object.entries(SPLIT)) {
    if (!files.has(path)) continue
    const entries = new Map()
    const rest = split(parse(path), (entry, kind, id) => {
      if (!kind || id == null || !known[kind].has(String(id))) return false
      const key = `${kind}:${id}`
      if (!entries.has(key)) entries.set(key, [])
      entries.get(key).push(entry)
      return true
    }, ctx)
    shared.push(`${path} ${hash(rest)}`)
    owned.set(path, new Map([...entries].map(([key, list], order) => [key, { order, hash: hash(list) }])))
  }
  const entityFiles = new Map()
  const refs = manifest.files?.refs
  const special = new Set(['manifest.json', refs, manifest.files.units, manifest.files.recipes, manifest.files.teammates, manifest.files.scenarios])
  const anchors = manifest.files?.anchors
  for (const path of [...files.keys()].sort()) {
    if (special.has(path) || owned.has(path) || (anchors && path.startsWith(anchors))) continue
    const dir = ENTITY_DIRS.find(([prefix]) => path.startsWith(prefix) && !path.slice(prefix.length).includes('/'))
    const id = dir && path.slice(dir[0].length).replace(/\.json$/, '')
    if (dir && known[dir[1]].has(id)) entityFiles.set(`${dir[1]}:${id}:${dir[0]}`, `${path} ${sha256(strip(text(path)))}`)
    else shared.push(`${path} ${sha256(strip(text(path)))}`)
  }

  const plans = parse(manifest.files.recipes)
  const teammates = parse(manifest.files.teammates)
  const selections = manifest.files.scenarios && files.has(manifest.files.scenarios) ? parse(manifest.files.scenarios) : {}
  const { id: _id, hashes: _hashes, gameVer: _gameVer, scenarios, ...rest } = manifest
  const base = [`manifest ${hash({ ...rest, files: withoutResults(rest.files) })}`,
    `plans ${hash({ ...plans, plans: null })}`, `teammates ${hash({ ...teammates, resonators: null })}`,
    `selections ${hash({ ...selections, resonators: null, teams: null })}`, ...shared]

  const result = {}
  for (const def of scenarios) {
    const { entities, builds } = scenarioEntities(def, teammates)
    const parts = [...base, `def ${hash(def)}`, `plan ${hash(plans.plans?.[def.teamId] ?? null)}`,
      `builds ${hash(Object.fromEntries(builds))}`,
      `selection ${hash({ resonator: selections.resonators?.[def.resonatorId] ?? null, team: selections.teams?.[def.teamId] ?? null })}`]
    for (const [path, byEntity] of owned) {
      // the entities' entries in file order, because a reader may depend on it
      const mine = entities.filter((key) => byEntity.has(key)).sort((a, b) => byEntity.get(a).order - byEntity.get(b).order)
      parts.push(`${path} ${mine.map((key) => `${key}=${byEntity.get(key).hash}`).join(' ')}`)
    }
    for (const key of entities) for (const [prefix, kind] of ENTITY_DIRS) {
      if (key.startsWith(`${kind}:`)) parts.push(entityFiles.get(`${key}:${prefix}`) ?? `${prefix} ${key} absent`)
    }
    result[def.id.slice(def.id.indexOf(':') + 1)] = sha256(parts.join('\n'))
  }
  return result
}
