export interface GuideSection {
  title: string
  blocks: GuideBlock[]
}

export interface GuideArticle {
  id: string
  title: string
  summary: string
  sections: GuideSection[]
}

export interface GuideCategory {
  id: string
  title: string
  summary: string
  aliases?: string[]
  articles: GuideArticle[]
}

export type GuideBlock =
  | {
    type: 'paragraph'
    text: string[]
  }
  | {
    type: 'bullets'
    items: string[]
  }
  | {
    type: 'definitions'
    items: Array<{ term: string, description: string }>
  }
  | {
    type: 'note'
    tone?: 'info' | 'warning'
    text: string
  }
  | {
    type: 'example'
    title: string
    setup: string[]
    observation: string[]
    takeaway: string[]
  }
  | {
    type: 'steps'
    items: Array<{ title: string, description: string }>
  }
  | {
    type: 'comparison'
    leftLabel: string
    rightLabel: string
    rows: Array<{ label: string, left: string, right: string }>
  }
  | {
    type: 'statTable'
    rows: Array<{
      stat: string
      structure: string
      meaning: string
      surfaces: string
    }>
  }
  | {
    type: 'warningList'
    items: string[]
  }
  | {
    type: 'image'
    src: string
    alt: string
    caption: string
  }
  | {
    type: 'plate'
    shot: string
    width: number
    height: number
    alt: string
    steps: GuidePlateStep[]
  }

// coordinates are [left, top, width, height] percentages in source-image space.
export interface GuidePlateStep {
  title: string
  description: string
  box: [number, number, number, number]
}

const paragraph = (...text: string[]): GuideBlock => ({ type: 'paragraph', text })
const note = (text: string, tone?: 'info' | 'warning'): GuideBlock => ({ type: 'note', tone, text })
const steps = (...items: Array<[string, string]>): GuideBlock => ({
  type: 'steps',
  items: items.map(([title, description]) => ({ title, description })),
})
const plate = (
  shot: string,
  [width, height]: [number, number],
  alt: string,
  ...steps: Array<[string, string, GuidePlateStep['box']]>
): GuideBlock => ({
  type: 'plate',
  shot,
  width,
  height,
  alt,
  steps: steps.map(([title, description, box]) => ({ title, description, box })),
})
const section = (title: string, ...blocks: GuideBlock[]): GuideSection => ({ title, blocks })
const article = (
  id: string,
  title: string,
  summary: string,
  ...sections: GuideSection[]
): GuideArticle => ({
  id,
  title,
  summary,
  sections,
})

